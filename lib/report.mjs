// Probe report (PLAN-REVIEW3.md C1): one Markdown document for a bug report. Every captured value is
// attacker-controlled, so it only ever appears inside inline code or a fenced block whose fence is
// longer than any backtick run in it; nothing captured can become a link, heading or HTML.
import { decodeExfil, decodeLabels } from "../web/src/lib/exfil.ts";
import { dnsSteps } from "../web/src/lib/dns.ts";

const MAX_RAW = 16 * 1024;

function ticks(s) { let n = 0; for (const m of s.matchAll(/`+/g)) n = Math.max(n, m[0].length); return n; }
// inline code: one line, fenced by more backticks than it contains
export function code(v, max = 300) {
  let s = String(v ?? "").replace(/\r?\n/g, "\\n").replace(/[\u0000-\u001f\u007f]/g, (c) => "\\x" + c.charCodeAt(0).toString(16).padStart(2, "0"));
  if (s.length > max) s = s.slice(0, max) + "…";
  const f = "`".repeat(ticks(s) + 1);
  const pad = /^`|`$/.test(s) || s === "" ? " " : "";
  return `${f}${pad}${s}${pad}${f}`;
}
export function fenced(text, lang = "") {
  let s = String(text ?? "");
  let note = "";
  const bytes = Buffer.byteLength(s);
  if (bytes > MAX_RAW) { s = Buffer.from(s).subarray(0, MAX_RAW).toString("utf8"); note = `\n_${bytes - MAX_RAW} more bytes not included; the full capture is in Colluder._\n`; }
  const f = "`".repeat(Math.max(3, ticks(s) + 1));
  return `${f}${lang}\n${s.replace(/\r\n/g, "\n")}\n${f}\n${note}`;
}

const hms = (iso) => iso.replace("T", " ").replace(/(\.\d{3})\d*Z$/, "$1");
const isWeb = (h) => h.protocol === "http" || h.protocol === "https";
const reqLine = (raw) => String(raw ?? "").split(/\r?\n/)[0];
const header = (raw, name) => {
  const head = String(raw ?? "").split(/\r?\n\r?\n/)[0].split(/\r?\n/).slice(1);
  const ln = head.find((l) => l.toLowerCase().startsWith(name + ":"));
  return ln ? ln.slice(name.length + 1).trim() : "";
};

export function answeredBy(a) {
  if (!a) return "sent by interactsh-server (its default reply)";
  if (a.mode === "error") return `refused by Colluder (${a.error ?? "bad request"})`;
  if (a.mode === "default") return "sent by Colluder (default reply)";
  const what = a.mode === "redirect" ? `redirect${a.hop ? `, hop ${a.hop}` : ""}` : a.mode === "file" ? "hosted file" : "custom response";
  return `sent by Colluder (rule v${a.version}, ${what})`;
}

// labels in front of the tag: the part of a DNS name the target (or its data) chose
function extraLabels(h) {
  const full = h.fullId.toLowerCase(), id = h.uniqueId.toLowerCase();
  if (!full.endsWith(id) || full === id) return [];
  const labels = full.slice(0, -id.length - 1).split(".");
  if (labels.at(-1) === h.tag) labels.pop();
  return labels;
}

export function probeReport({ probe, hits, trigger, enrich, domain, payloadId, selfIps = [], now }) {
  const self = new Set(selfIps);
  const who = (ip) => {
    const e = enrich(ip) || {};
    const bits = [e.rdns && `rDNS ${code(e.rdns, 120)}`, e.asn && `${e.asn}${e.asnName ? " " + code(e.asnName, 80) : ""}${e.asnCc ? " " + e.asnCc : ""}`, self.has(ip) && "this OOB box (a self-test)"].filter(Boolean);
    return `${code(ip)}${bits.length ? " (" + bits.join(", ") + ")" : ""}`;
  };
  const steps = dnsSteps(hits);
  const web = hits.filter(isWeb);
  const dns = hits.filter((h) => h.protocol === "dns");
  const counts = Object.entries(hits.reduce((m, h) => ({ ...m, [h.protocol]: (m[h.protocol] || 0) + 1 }), {})).map(([p, n]) => `${n} ${p.toUpperCase()}`).join(", ");
  const tag = probe.tag;
  const out = [];

  out.push(`# Out-of-band interaction report: probe ${code(tag)}`, "");
  out.push(`Generated by Colluder at ${hms(now)} UTC. All times are UTC.`, "");
  out.push("## Summary", "");
  out.push(`- **Payloads:** ${code(`${tag}.${payloadId}.${domain}`)} (DNS, HTTP) and ${code(`https://${payloadId}.${domain}/${tag}/`)} (HTTPS)`);
  out.push(`- **Planted:** ${hms(probe.plantedAt)}${probe.target ? ` in ${code(probe.target)}` : ""}`);
  if (probe.note) out.push(`- **Note:** ${code(probe.note, 500)}`);
  out.push(hits.length ? `- **Hits:** ${hits.length} (${counts}), first ${hms(hits[0].timestamp)}, last ${hms(hits.at(-1).timestamp)}` : "- **Hits:** none recorded");
  const webSources = [...new Set(web.map((h) => h.remoteAddress))];
  if (webSources.length) out.push(`- **Web requests came from:** ${webSources.map(who).join("; ")}`);
  out.push("");

  out.push("## Triggering request", "");
  out.push(trigger ? fenced(trigger, "http") : "_Not recorded. Paste the request that triggered the callback into the probe's Trigger field in Colluder._\n");

  out.push("## Timeline", "");
  out.push(`- ${code(hms(probe.plantedAt))} Probe planted.`);
  const firstDns = dns.find((h) => !steps.has(h.id));
  if (firstDns) out.push(`- ${code(hms(firstDns.timestamp))} First DNS lookup (${firstDns.qType || "other"}) of ${code(firstDns.fullId)}, asked by resolver ${who(firstDns.remoteAddress)}. (#${firstDns.id})`);
  // a web request is a timeline event when it is the first at all, from a new source, or of a new protocol
  const sources = new Set(), protos = new Set();
  for (const h of web) {
    const newSource = !sources.has(h.remoteAddress), newProto = !protos.has(h.protocol);
    if (!newSource && !newProto) continue;
    const lead = !sources.size ? "First" : newSource ? "New source:" : "First";
    sources.add(h.remoteAddress); protos.add(h.protocol);
    const ua = header(h.rawRequest, "user-agent");
    out.push(`- ${code(hms(h.timestamp))} ${lead} ${h.protocol.toUpperCase()} request from ${who(h.remoteAddress)}: ${code(reqLine(h.rawRequest))}${ua ? `, User-Agent ${code(ua, 200)}` : ""}. (#${h.id})`);
  }
  const shownExfil = new Set();
  for (const h of dns) {
    if (steps.has(h.id)) continue;
    for (const { label, decoded } of decodeLabels(extraLabels(h))) {
      if (shownExfil.has(label)) continue;
      shownExfil.add(label);
      out.push(`- ${code(hms(h.timestamp))} DNS name carried data: ${code(label)} decodes as ${decoded.kind} to ${code(decoded.text)}. (#${h.id})`);
    }
  }
  for (const h of web) {
    const q = reqLine(h.rawRequest).split(" ")[1]?.split("?")[1];
    for (const kv of (q ?? "").split("&")) {
      const v = kv.split("=")[1];
      if (!v) continue;
      let raw = v; try { raw = decodeURIComponent(v); } catch { /* keep */ }
      const d = decodeExfil(raw);
      if (d && !shownExfil.has(raw)) { shownExfil.add(raw); out.push(`- ${code(hms(h.timestamp))} Query value carried data: ${code(raw, 120)} decodes as ${d.kind} to ${code(d.text)}. (#${h.id})`); }
    }
  }
  if (hits.length) out.push(`- ${code(hms(hits.at(-1).timestamp))} Last hit. (#${hits.at(-1).id})`);
  out.push("");

  const resolvers = new Map();
  for (const h of dns) resolvers.set(h.remoteAddress, (resolvers.get(h.remoteAddress) || 0) + 1);
  if (resolvers.size) {
    out.push("## DNS resolvers", "");
    out.push("DNS lookups come from the resolver that asked on the target's behalf, often a public or ISP resolver rather than the target itself.", "");
    for (const [ip, n] of [...resolvers].sort((a, b) => b[1] - a[1]).slice(0, 12)) out.push(`- ${who(ip)}: ${n} ${n === 1 ? "lookup" : "lookups"}`);
    if (resolvers.size > 12) out.push(`- and ${resolvers.size - 12} more`);
    out.push("");
  }

  const first = web.find((h) => !self.has(h.remoteAddress)) ?? web[0];
  if (first) {
    out.push(`## ${first === web[0] ? "First" : "First non-self-test"} web request (#${first.id})`, "");
    out.push(first.answer
      ? "Captured by Colluder's edge: these are the exact bytes as received."
      : "Captured by interactsh-client: header order and name case were normalised by interactsh, so they are not the wire's.");
    out.push(`Received ${hms(first.timestamp)} from ${who(first.remoteAddress)}. SHA-256 of the request at ingest: ${code(first.reqSha256)}.`, "");
    out.push(fenced(first.rawRequest, "http"));
    out.push(`Response, ${answeredBy(first.answer)}:`, "");
    out.push(fenced(first.rawResponse, "http"));
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
